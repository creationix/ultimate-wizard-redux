// Regenerates src/solutions.js: a verified, frame-exact winning input recording
// for every built-in level (one that simply wins, one that also takes every gem).
//   npm run solve            solve levels whose map changed since the last run
//   npm run solve -- --all   re-solve everything
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../src/levels.js';
import { validateLevel, levelHash, replay } from '../src/sim.js';
import { solve } from '../src/solver.js';

let old = {};
try { old = (await import('../src/solutions.js')).SOLUTIONS; } catch { /* first run */ }
const all = process.argv.includes('--all');
const out = {};
let failed = false;
for (const def of LEVELS) {
  const errs = validateLevel(def);
  if (errs.length) { console.error(`✗ ${def.id}: ${errs.join('; ')}`); failed = true; continue; }
  const hash = levelHash(def), prev = old[def.id];
  if (!all && prev && prev.hash === hash && prev.win && prev.perfect) { out[def.id] = prev; console.log(`= ${def.id} unchanged`); continue; }
  const entry = { hash };
  for (const mode of ['win', 'perfect']) {
    const t = Date.now();
    const r = solve(def, { perfect: mode === 'perfect' });
    if (!r.ok) { console.error(`✗ ${def.id} ${mode}: ${r.reason}`); failed = true; continue; }
    const s = replay(def, r.inputs);
    if (!s.won) throw new Error(`${def.id}: solver returned a recording that does not win`);
    entry[mode] = r.inputs;
    console.log(`✓ ${def.id} ${mode}: ${(r.frames / 60).toFixed(1)}s, ${s.gems} gems, ${r.nodes} nodes, ${Date.now() - t}ms`);
  }
  // A perfect run is also a winning run; fall back to it if the plain search missed.
  if (!entry.win && entry.perfect) entry.win = entry.perfect;
  out[def.id] = entry;
}
const body = Object.entries(out).map(([id, e]) => `  ${JSON.stringify(id)}: ${JSON.stringify(e)},`).join('\n');
writeFileSync(new URL('../src/solutions.js', import.meta.url),
  `// GENERATED by \`npm run solve\` - do not edit by hand.\n// Run-length encoded input recordings [mask, frames, ...] pinned to a hash of each level.\nexport const SOLUTIONS = {\n${body}\n};\n`);
process.exit(failed ? 1 : 0);
